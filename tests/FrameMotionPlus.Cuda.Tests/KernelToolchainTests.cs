using System.Security.Cryptography;
using FrameMotionPlus.Core.Frames;
using FrameMotionPlus.Cuda.Kernels;
using FrameMotionPlus.Cuda.Tests.Support;

namespace FrameMotionPlus.Cuda.Tests;

/// <summary>
/// The checked-in PTX against its sources. The manifest check needs no toolchain and so runs on CI: editing a kernel
/// without regenerating fails there. Where the recorded toolchain is installed, a rebuild must reproduce the PTX byte
/// for byte; where nvcc is available, its build of the same sources must compute the same pixels.
/// </summary>
[Collection(SerialGpuDefinition.Name)]
public class KernelToolchainTests
{
    private sealed record Manifest(string Toolchain, string Version, Dictionary<string, string> Sources, Dictionary<string, string> Ptx);

    [Fact]
    public void Manifest_matches_the_sources_the_ptx_and_the_embedded_resources()
    {
        var dir = Repo.KernelsDirectory;
        var manifest = ReadManifest(Path.Combine(dir, "ptx", "manifest.txt"));

        var sources = Directory.GetFiles(dir, "*.cu").Select(Path.GetFileName).Append("fmp_cuda.h").Order(StringComparer.Ordinal);
        Assert.Equal(sources, manifest.Sources.Keys.Order(StringComparer.Ordinal));
        foreach (var (file, hash) in manifest.Sources)
        {
            Assert.True(hash == Sha256(Path.Combine(dir, file)), $"{file} changed since the PTX was generated: run native/kernels/build.sh");
        }

        var ptxFiles = Directory.GetFiles(Path.Combine(dir, "ptx"), "*.ptx").Select(Path.GetFileName).Order(StringComparer.Ordinal);
        Assert.Equal(ptxFiles, manifest.Ptx.Keys.Order(StringComparer.Ordinal));
        Assert.Equal(ImageKernels.ModuleNames.Select(m => m + ".ptx"), manifest.Ptx.Keys.Order(StringComparer.Ordinal));
        foreach (var (file, hash) in manifest.Ptx)
        {
            var path = Path.Combine(dir, "ptx", file);
            Assert.True(hash == Sha256(path), $"{file} was edited by hand or regenerated without its manifest");
            Assert.Equal(File.ReadAllBytes(path), ImageKernels.GetEmbeddedPtx(Path.GetFileNameWithoutExtension(file)));
        }
    }

    [Fact]
    public void Rebuilding_with_the_recorded_toolchain_reproduces_the_checked_in_ptx()
    {
        var dir = Repo.KernelsDirectory;
        var manifest = ReadManifest(Path.Combine(dir, "ptx", "manifest.txt"));
        var bash = Tools.Which("bash");
        if (bash is null || OperatingSystem.IsWindows())
        {
            Assert.Skip("needs bash");
        }

        var arguments = new List<string> { Path.Combine(dir, "build.sh"), "--toolchain", manifest.Toolchain };
        if (manifest.Toolchain == "clang")
        {
            var clang = Environment.GetEnvironmentVariable("FMP_CLANG") ?? "clang";
            var clangPath = Tools.Which(clang);
            if (clangPath is null)
            {
                Assert.Skip("clang not installed");
            }

            var version = Tools.Run(clangPath, ["--version"]).Output;
            if (!version.Contains($"version {manifest.Version}", StringComparison.Ordinal))
            {
                Assert.Skip($"PTX was generated by clang {manifest.Version}; installed: {version.Split('\n')[0]}");
            }
        }
        else
        {
            var toolkit = Repo.CudaToolkit;
            if (toolkit is null)
            {
                Assert.Skip("nvcc toolkit not found");
            }

            arguments.AddRange(["--cuda-path", toolkit]);
        }

        var output = Tools.TempDirectory("ptx");
        try
        {
            arguments.AddRange(["--out", output]);
            var (exit, log) = Tools.Run(bash, arguments);
            Assert.True(exit == 0, log);
            var rebuilt = ReadManifest(Path.Combine(output, "manifest.txt"));
            if (rebuilt.Version != manifest.Version)
            {
                Assert.Skip($"PTX was generated by {manifest.Toolchain} {manifest.Version}; installed: {rebuilt.Version}");
            }

            foreach (var file in manifest.Ptx.Keys)
            {
                Assert.True(
                    File.ReadAllBytes(Path.Combine(dir, "ptx", file)).AsSpan().SequenceEqual(File.ReadAllBytes(Path.Combine(output, file))),
                    $"{file} is stale: run native/kernels/build.sh");
            }

            Assert.Equal(File.ReadAllText(Path.Combine(dir, "ptx", "manifest.txt")), File.ReadAllText(Path.Combine(output, "manifest.txt")));
        }
        finally
        {
            Directory.Delete(output, recursive: true);
        }
    }

    [Fact]
    [Trait("Category", "Gpu")]
    public void Nvcc_build_of_the_same_sources_loads_and_computes_identical_pixels()
    {
        var env = Gpu.Require();
        var bash = Tools.Which("bash");
        var toolkit = Repo.CudaToolkit;
        if (toolkit is null || !File.Exists(Path.Combine(toolkit, "bin", "nvcc")) || bash is null)
        {
            Assert.Skip("nvcc toolkit not found");
        }

        var output = Tools.TempDirectory("nvcc");
        try
        {
            var (exit, log) = Tools.Run(bash, [Path.Combine(Repo.KernelsDirectory, "build.sh"), "--toolchain", "nvcc", "--cuda-path", toolkit, "--out", output]);
            Assert.True(exit == 0, log);
            using var nvcc = ImageKernels.Load(env.Context, module => File.ReadAllBytes(Path.Combine(output, module + ".ptx")));
            using var stream = CudaStream.Create(env.Context);
            foreach (var format in new[] { PixelFormat.Rgba8, PixelFormat.Bgra8, PixelFormat.Rgb10A2 })
            {
                const int Width = 517, Height = 211;
                using var a = env.Image(Width, Height, format);
                using var b = env.Image(Width, Height, format);
                using var o = env.Image(Width, Height, format);
                using var c = env.Image(Width, Height, format == PixelFormat.Rgb10A2 ? PixelFormat.Rgba8 : PixelFormat.Rgb10A2);
                nvcc.EnqueueTestPattern(stream, a.AsFrame(), 41);
                Assert.Equal(Reference.Pattern(Width, Height, 41, format), env.Read(stream, a.AsFrame()));
                nvcc.EnqueueTestPattern(stream, b.AsFrame(), 42);
                nvcc.EnqueueBlend(stream, a.AsFrame(), b.AsFrame(), 0.3f, o.AsFrame());
                var nvccBlend = env.Read(stream, o.AsFrame());
                env.Kernels.EnqueueBlend(stream, a.AsFrame(), b.AsFrame(), 0.3f, o.AsFrame());
                Assert.Equal(env.Read(stream, o.AsFrame()), nvccBlend);
                nvcc.EnqueueConvert(stream, a.AsFrame(), c.AsFrame());
                Assert.Equal(Reference.Convert(Reference.Pattern(Width, Height, 41, format), format, c.Format), env.Read(stream, c.AsFrame()));
            }
        }
        finally
        {
            Directory.Delete(output, recursive: true);
        }
    }

    private static Manifest ReadManifest(string path)
    {
        string? toolchain = null, version = null;
        var sources = new Dictionary<string, string>(StringComparer.Ordinal);
        var ptx = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var line in File.ReadAllLines(path))
        {
            var parts = line.Split(' ');
            switch (parts[0])
            {
                case "toolchain":
                    (toolchain, version) = (parts[1], parts[2]);
                    break;
                case "source":
                    sources.Add(parts[1], parts[2]);
                    break;
                case "ptx":
                    ptx.Add(parts[1], parts[2]);
                    break;
                default:
                    break;
            }
        }

        Assert.NotNull(toolchain);
        Assert.NotNull(version);
        return new Manifest(toolchain, version, sources, ptx);
    }

    private static string Sha256(string path) => Convert.ToHexStringLower(SHA256.HashData(File.ReadAllBytes(path)));
}
